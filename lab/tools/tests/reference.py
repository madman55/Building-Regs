"""Phase 1 gate: labels and edition on every result, document status, saved items, report links,
lesson references opening the exact block, and the switch turning it all off."""
import os, threading, http.server, functools, urllib.parse
from playwright.sync_api import sync_playwright
APP = os.environ.get('APP_DIR', '.')
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 8781), functools.partial(Q, directory=APP))
threading.Thread(target=srv.serve_forever, daemon=True).start()
ok = True
def check(name, cond, extra=''):
    global ok
    ok &= bool(cond); print(('PASS ' if cond else 'FAIL ') + name + (('   ' + str(extra)) if extra and not cond else ''))
def search(pg, q):
    pg.fill('#sq', q); pg.wait_for_timeout(700)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 390, 'height': 820}); pg = ctx.new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)[:200])); ctx.route('https://**', lambda r: r.abort())
    pg.goto('http://localhost:8781/'); pg.wait_for_timeout(600)
    pg.evaluate("document.getElementById('splash')&&document.getElementById('splash').click()"); pg.wait_for_timeout(400)
    pg.click('[data-lv="std"]'); pg.wait_for_timeout(300); pg.click('.sbtn'); pg.wait_for_timeout(1500)
    check('start screen lists the documents', pg.locator('.labdoc').count() == 3)
    for q in ['second staircase block of flats', 'rise and going', 'requirement for means of warning and escape', 'fire door in a house']:
        search(pg, q)
        cards = pg.locator('.sr.off'); n = cards.count(); smalls = [cards.nth(i).locator('small').inner_text() for i in range(n)]
        labelled = all(cards.nth(i).locator('.lab-guide, .lab-law').count() == 1 for i in range(n))
        dated = all(('2013 edition' in t) or ('2019 ed.' in t) for t in smalls)
        check(f'"{q}": all {n} official results show edition and label', n and labelled and dated, smalls[:2])
        les = pg.locator('.sr:not(.off)')
        check(f'"{q}": lesson results labelled Explanation', les.count() == 0 or all(les.nth(i).locator('.lab-expl').count() == 1 for i in range(les.count())))
    search(pg, 'requirement for means of warning and escape')
    check('a requirement is labelled Law', pg.locator('.sr.off .lab-law').count() >= 1)
    pg.click('[data-lab="legend"]'); pg.wait_for_timeout(300)
    t = pg.inner_text('.sheet'); check('label legend explains all four labels', all(w in t for w in ['Law', 'Statutory guidance', 'Explanation', 'Fictional', 'section 7']))
    pg.click('.sheet [data-close]'); pg.wait_for_timeout(300)
    search(pg, 'second staircase block of flats'); pg.locator('.sr.off').first.click(); pg.wait_for_timeout(3500)
    vf = pg.inner_text('#labvf'); check('viewer shows document, edition and label', '2019 ed.' in vf and ('Statutory guidance' in vf or 'Law' in vf), vf)
    check('report links hidden while feedback is informal', pg.locator('#labrep').count() == 0)
    pg.click('#labstar'); pg.wait_for_timeout(300)
    check('star saves the item', pg.get_attribute('#labstar', 'aria-pressed') == 'true')
    pg.click('[data-lab="info"]'); pg.wait_for_timeout(300)
    t = pg.inner_text('.sheet').lower()
    check('status sheet: edition, jurisdiction, not yet in force, transition, copy date', all(w in t for w in ['2019 edition incorporating', 'england only', '2 september 2029', 'earlier rules still apply', 'copy in this app made']), t[:300])
    pg.click('.sheet [data-close]'); pg.wait_for_timeout(300)
    pg.click('#dvnext'); pg.wait_for_timeout(1500)
    check('page turn: star shows the new page is not saved', pg.get_attribute('#labstar', 'aria-pressed') == 'false')
    pg.click('#dvx'); pg.wait_for_timeout(300)
    search(pg, ''); pg.wait_for_timeout(300)
    check('saved item listed on the start screen', pg.locator('.labbm').count() == 1 and 'Diagram 3.8' in pg.inner_text('.labbm'), pg.inner_text('#sres')[:200])
    pg.click('.labbm-open'); pg.wait_for_timeout(3000)
    check('saved item opens highlighted', pg.locator('.dvmark').count() == 1 and pg.get_attribute('#labstar', 'aria-pressed') == 'true')
    pg.click('#dvx'); pg.wait_for_timeout(300)
    pg.evaluate("(()=>{const k='regs-lab-bookmarks',v=JSON.parse(localStorage.getItem(k));v[0].sig='changed';localStorage.setItem(k,JSON.stringify(v))})()")
    pg.reload(); pg.wait_for_timeout(1200); pg.evaluate("document.getElementById('splash')&&document.getElementById('splash').click()"); pg.wait_for_timeout(300)
    pg.click('.sbtn'); pg.wait_for_timeout(1500)
    check('changed wording is flagged on the saved item', 'Moved or changed' in pg.inner_text('.labbm'))
    pg.click('.labbm-x'); pg.wait_for_timeout(300)
    check('saved item can be removed', pg.locator('.labbm').count() == 0)
    attr = pg.evaluate("LABREF.blk('AD B Vol 1, Table 3.1')")
    check('lesson reference resolves to the exact table', 'data-blk' in attr, attr)
    pg.evaluate("""(()=>{const id=LABREF.refBlock('AD B Vol 1, Table 3.1').id,b=document.createElement('button');b.className='linkb adp';b.dataset.doc='B1';b.dataset.adp='';b.dataset.blk=id;b.id='tref';document.body.appendChild(b)})()""")
    pg.evaluate("document.getElementById('tref').click()"); pg.wait_for_timeout(3000)
    check('lesson link opens that table highlighted', 'Table 3.1' in pg.inner_text('.dvt b') and pg.locator('.dvmark').count() == 1, pg.inner_text('.dvt b'))
    pg.click('#dvx'); pg.wait_for_timeout(300)
    pg.locator('nav.tabs button').last.click(); pg.wait_for_timeout(500)
    pg.click('[data-labf="reference"]'); pg.wait_for_timeout(300)
    check('Profile switch turns reference upgrades off', pg.get_attribute('[data-labf="reference"]', 'aria-checked') == 'false')
    pg.locator('nav.tabs button').first.click(); pg.wait_for_timeout(500)
    pg.click('.sbtn'); pg.wait_for_timeout(1200)
    check('switched off: start screen back to normal', pg.locator('.labdoc').count() == 0)
    search(pg, 'second staircase block of flats')
    check('switched off: no labels or edition on results', pg.locator('.sr.off .kd.lab-guide, .sr.off .kd.lab-law').count() == 0 and '2019 ed.' not in pg.inner_text('#sres'))
    pg.locator('.sr.off').first.click(); pg.wait_for_timeout(2500)
    check('switched off: viewer has no star or report link', pg.locator('#labstar').count() == 0 and pg.locator('#labrep').count() == 0)
    check('no page errors', not errs, errs)
    b.close()
srv.shutdown()
print('GATE PASSED' if ok else 'GATE FAILED')
